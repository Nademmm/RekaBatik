-- Batik catalog
CREATE TABLE IF NOT EXISTS batik_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  price NUMERIC,
  description TEXT,
  origin TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  rating INT DEFAULT 5,
  sold INT DEFAULT 0,
  style_type TEXT,
  image_url TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Custom designs
CREATE TABLE IF NOT EXISTS custom_designs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  pattern_id INT,
  colors JSONB,
  scale INT,
  rotation INT,
  drawing_data TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Artisan stores
CREATE TABLE IF NOT EXISTS stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner TEXT,
  owner_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  established TEXT,
  specialty TEXT,
  address TEXT,
  phone TEXT,
  hours TEXT,
  rating INT DEFAULT 5,
  review_count INT DEFAULT 0,
  price_range TEXT,
  tags TEXT[],
  image TEXT,
  hero_image TEXT,
  gallery TEXT[],
  team TEXT[],
  featured BOOLEAN DEFAULT FALSE,
  description TEXT,
  motifs TEXT[]
);

-- Orders
CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  item TEXT NOT NULL,
  description TEXT,
  date TIMESTAMPTZ DEFAULT NOW(),
  delivered_date TIMESTAMPTZ,
  estimated_date TIMESTAMPTZ,
  status TEXT DEFAULT 'processing'
    CHECK (status IN ('negotiating', 'processing', 'shipping', 'delivered', 'cancelled')),
  total NUMERIC,
  type TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  artisan TEXT,
  can_review BOOLEAN DEFAULT FALSE,
  reviewed BOOLEAN DEFAULT FALSE,
  payment_method TEXT DEFAULT 'transfer_bca'
    CHECK (payment_method IN ('transfer_bca', 'transfer_mandiri', 'gopay', 'ovo', 'cod') OR payment_method IS NULL),
  payment_status TEXT DEFAULT 'pending'
    CHECK (payment_status IN ('pending', 'awaiting_verification', 'paid', 'failed') OR payment_status IS NULL),
  shipping_address JSONB,
  quantity INT DEFAULT 1,
  notes TEXT,
  tracking_number VARCHAR(100),
  courier VARCHAR(50),
  review_rating INTEGER,
  review_comment TEXT,
  custom_design_id BIGINT REFERENCES custom_designs(id) ON DELETE SET NULL
);

-- Cart
CREATE TABLE IF NOT EXISTS cart_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  batik_id BIGINT REFERENCES batik_items(id) ON DELETE CASCADE,
  custom_design_id BIGINT REFERENCES custom_designs(id) ON DELETE CASCADE,
  quantity INT DEFAULT 1 CHECK (quantity > 0),
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Chat / negotiation
CREATE TABLE IF NOT EXISTS messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id TEXT REFERENCES orders(id) ON DELETE CASCADE,
  sender_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  sender_role TEXT NOT NULL CHECK (sender_role IN ('user', 'artisan')),
  message TEXT NOT NULL,
  price_offer NUMERIC,
  negotiation_status TEXT CHECK (negotiation_status IN ('pending', 'accepted', 'rejected')),
  status TEXT DEFAULT 'sent' CHECK (status IN ('sent', 'delivered', 'read')),
  attachment TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Landing page reviews
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT,
  image TEXT,
  rating INT DEFAULT 5,
  comment TEXT,
  product TEXT,
  date TEXT
);

-- User address book
CREATE TABLE IF NOT EXISTS user_addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  label VARCHAR(50) NOT NULL DEFAULT 'Rumah',
  recipient_name VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  street TEXT NOT NULL,
  city VARCHAR(100) NOT NULL,
  province VARCHAR(100) NOT NULL,
  postal_code VARCHAR(10) NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- Favorites
CREATE TABLE IF NOT EXISTS favorite_batik (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  batik_id BIGINT REFERENCES batik_items(id) ON DELETE CASCADE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  UNIQUE(user_id, batik_id)
);

CREATE TABLE IF NOT EXISTS favorite_stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  store_id BIGINT REFERENCES stores(id) ON DELETE CASCADE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  UNIQUE(user_id, store_id)
);


