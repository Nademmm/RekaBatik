-- REKABATIK — CREATE PREMIUM SUBSCRIPTIONS TABLE
-- =====================================================
-- Run this in your Supabase SQL Editor to enable admin-verified premium billing.

CREATE TABLE IF NOT EXISTS premium_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  user_email TEXT,
  user_name TEXT,
  plan_id TEXT CHECK (plan_id IN ('weekly', 'monthly')) NOT NULL,
  price NUMERIC NOT NULL,
  sender_name TEXT NOT NULL,
  bank_from TEXT NOT NULL,
  transfer_date DATE DEFAULT CURRENT_DATE,
  notes TEXT,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  attachment_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL
);

-- Enable RLS
ALTER TABLE premium_subscriptions ENABLE ROW LEVEL SECURITY;

-- Policy: Users can insert their own subscriptions
CREATE POLICY "Users can insert their own subscriptions" 
ON premium_subscriptions FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = user_id);

-- Policy: Users can view their own subscriptions
CREATE POLICY "Users can view their own subscriptions" 
ON premium_subscriptions FOR SELECT 
TO authenticated 
USING (auth.uid() = user_id);

-- Policy: Super Admins can do everything
CREATE POLICY "Super Admins can manage all subscriptions" 
ON premium_subscriptions FOR ALL 
TO authenticated 
USING (
  coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '') = 'super_admin'
);
