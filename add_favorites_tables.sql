  -- ==========================================
  -- ADD FAVORITES TABLES TO REKABATIK SCHEMA
  -- ==========================================

  -- 1. Table for Favorite Batik Items
  CREATE TABLE IF NOT EXISTS favorite_batik (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    batik_id BIGINT REFERENCES batik_items(id) ON DELETE CASCADE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    UNIQUE(user_id, batik_id)
  );

  -- Enable RLS for Favorite Batik
  ALTER TABLE favorite_batik ENABLE ROW LEVEL SECURITY;

  DROP POLICY IF EXISTS "Users can view their own favorite batik" ON favorite_batik;
  DROP POLICY IF EXISTS "Users can insert their own favorite batik" ON favorite_batik;
  DROP POLICY IF EXISTS "Users can delete their own favorite batik" ON favorite_batik;

  CREATE POLICY "Users can view their own favorite batik"
  ON favorite_batik FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

  CREATE POLICY "Users can insert their own favorite batik"
  ON favorite_batik FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

  CREATE POLICY "Users can delete their own favorite batik"
  ON favorite_batik FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);

  -- 2. Table for Favorite Stores
  CREATE TABLE IF NOT EXISTS favorite_stores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    store_id BIGINT REFERENCES stores(id) ON DELETE CASCADE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    UNIQUE(user_id, store_id)
  );

  -- Enable RLS for Favorite Stores
  ALTER TABLE favorite_stores ENABLE ROW LEVEL SECURITY;

  DROP POLICY IF EXISTS "Users can view their own favorite stores" ON favorite_stores;
  DROP POLICY IF EXISTS "Users can insert their own favorite stores" ON favorite_stores;
  DROP POLICY IF EXISTS "Users can delete their own favorite stores" ON favorite_stores;

  CREATE POLICY "Users can view their own favorite stores"
  ON favorite_stores FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

  CREATE POLICY "Users can insert their own favorite stores"
  ON favorite_stores FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

  CREATE POLICY "Users can delete their own favorite stores"
  ON favorite_stores FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);
