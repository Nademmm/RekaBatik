-- ==========================================
-- REKABATIK SUPABASE DATABASE SCHEMA
-- ==========================================

-- 1. Table for Batik Catalog
CREATE TABLE IF NOT EXISTS batik_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  price NUMERIC,
  description TEXT,
  origin TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  rating INT DEFAULT 5,
  sold INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Table for Orders
CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  item TEXT NOT NULL,
  description TEXT,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  delivered_date TIMESTAMP WITH TIME ZONE,
  estimated_date TIMESTAMP WITH TIME ZONE,
  status TEXT CHECK (status IN ('delivered', 'shipping', 'processing')),
  total NUMERIC,
  type TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  artisan TEXT,
  can_review BOOLEAN DEFAULT FALSE,
  reviewed BOOLEAN DEFAULT FALSE
);

-- 3. Table for Artisan Stores
CREATE TABLE IF NOT EXISTS stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner TEXT,
  established TEXT,
  specialty TEXT,
  address TEXT,
  phone TEXT,
  hours TEXT,
  rating INT DEFAULT 5,
  review_count INT DEFAULT 0,
  price_range TEXT,
  tags TEXT[], -- Array of strings for tags
  image TEXT,
  featured BOOLEAN DEFAULT FALSE,
  description TEXT,
  motifs TEXT[] -- Array of strings for featured motifs
);

-- 4. Table for User Reviews
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT,
  image TEXT,
  rating INT DEFAULT 5,
  comment TEXT,
  product TEXT,
  date TEXT
);

-- 5. Table for Custom Designs
CREATE TABLE IF NOT EXISTS custom_designs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pattern_id INT,
  colors JSONB,
  scale INT,
  rotation INT,
  drawing_data TEXT, -- Base64 string of drawing canvas
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

