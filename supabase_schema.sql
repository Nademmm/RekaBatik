-- ==========================================
-- REKABATIK SUPABASE DATABASE SCHEMA
-- ==========================================

-- 1. Table for Batik Catalog
CREATE TABLE IF NOT EXISTS batik_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  price NUMERIC,
  description TEXT,
  origin TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  rating INT DEFAULT 5,
  sold INT DEFAULT 0,
  style_type TEXT, -- Kolom baru untuk mapping visual SVG
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Table for Orders
CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id),
  item TEXT NOT NULL,
  description TEXT,
  date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  delivered_date TIMESTAMP WITH TIME ZONE,
  estimated_date TIMESTAMP WITH TIME ZONE,
  status TEXT CHECK (status IN ('delivered', 'shipping', 'processing')),
  total NUMERIC,
  type TEXT,
  primary_color TEXT,
  secondary_color TEXT,
  bg_color TEXT,
  artisan TEXT,
  can_review BOOLEAN DEFAULT FALSE,
  reviewed BOOLEAN DEFAULT FALSE
);

-- Enable RLS for Orders
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own orders" ON orders;
DROP POLICY IF EXISTS "Users can insert their own orders" ON orders;

CREATE POLICY "Users can view their own orders"
ON orders FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own orders"
ON orders FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- 3. Table for Artisan Stores
CREATE TABLE IF NOT EXISTS stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner TEXT,
  established TEXT,
  specialty TEXT,
  address TEXT,
  phone TEXT,
  hours TEXT,
  rating INT DEFAULT 5,
  review_count INT DEFAULT 0,
  price_range TEXT,
  tags TEXT[], -- Array of strings for tags
  image TEXT,
  featured BOOLEAN DEFAULT FALSE,
  description TEXT,
  motifs TEXT[] -- Array of strings for featured motifs
);

-- 4. Table for User Reviews
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT,
  image TEXT,
  rating INT DEFAULT 5,
  comment TEXT,
  product TEXT,
  date TEXT
);

-- 5. Table for Custom Designs
CREATE TABLE IF NOT EXISTS custom_designs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id),
  pattern_id INT,
  colors JSONB,
  scale INT,
  rotation INT,
  drawing_data TEXT, -- Base64 string of drawing canvas
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS for Custom Designs
ALTER TABLE custom_designs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own custom designs" ON custom_designs;
DROP POLICY IF EXISTS "Users can insert their own custom designs" ON custom_designs;
DROP POLICY IF EXISTS "Users can update their own custom designs" ON custom_designs;
DROP POLICY IF EXISTS "Users can delete their own custom designs" ON custom_designs;

CREATE POLICY "Users can view their own custom designs"
ON custom_designs FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own custom designs"
ON custom_designs FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own custom designs"
ON custom_designs FOR UPDATE
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can delete their own custom designs"
ON custom_designs FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

-- 6. Table for Cart Items
CREATE TABLE IF NOT EXISTS cart_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id),
  batik_id BIGINT REFERENCES batik_items(id),
  custom_design_id BIGINT REFERENCES custom_designs(id),
  quantity INT DEFAULT 1,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS for Cart Items
ALTER TABLE cart_items ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own cart items"
ON cart_items FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own cart items"
ON cart_items FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own cart items"
ON cart_items FOR UPDATE
TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can delete their own cart items"
ON cart_items FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

